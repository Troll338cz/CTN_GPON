# the same per-4-byte-word swap before it matches the rest of the image.

asmraw = b""
for n in func_asm.split("\n"):
    asmraw += bytes.fromhex(n[10:].replace(" ", ""))

if len(asmraw) % 4 != 0:
    raise ValueError(f"asmraw length {len(asmraw)} is not a multiple of 4 -- "
                      f"check func_asm for a missing/extra byte before swapping")

asmraw_swapped = bytearray(len(asmraw))
for i in range(0, len(asmraw), 4):
    asmraw_swapped[i:i+4] = asmraw[i:i+4][::-1]
asmraw_swapped = bytes(asmraw_swapped)

with open("patch.bin", "wb") as f:
    f.write(asmraw_swapped)

